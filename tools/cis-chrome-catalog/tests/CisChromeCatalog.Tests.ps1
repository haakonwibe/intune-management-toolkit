Describe 'Compare-CisChromePolicy' {
    BeforeAll {
        $script:Mapped = Invoke-CisChromeMapping -Recommendations $Recs -GpoPolicies $Gpo -Index $Index
        $script:Actual = Get-Content (Join-Path $Fixtures 'policy-actual.json') -Raw | ConvertFrom-Json -Depth 50
        $script:Diff = @(Compare-CisChromePolicy -ExpectedSettings $Mapped.Settings -Policy $Actual -Coverage $Mapped.Coverage)
        function Result([string]$Suffix) { ($script:Diff | Where-Object DefinitionId -eq "$($script:P)$Suffix").Result }
    }

    It 'reports Match for identical settings' {
        Result '_syncdisabled' | Should -Be 'Match'
        Result '~extensions_extensioninstallblocklist' | Should -Be 'Match'
        Result '_certificatetransparencyenforcementdisabledforcas' | Should -Be 'Match'
    }

    It 'reports WrongValue for a different child value or root state' {
        Result '_diskcachesize' | Should -Be 'WrongValue'
        ($Diff | Where-Object DefinitionId -eq "${P}_diskcachesize").Notes | Should -Match 'expected 250609664, actual 104857600'
        Result '_remotedebuggingallowed' | Should -Be 'WrongValue'
    }

    It 'reports Missing for expected settings the policy lacks' {
        Result '_proxysettings' | Should -Be 'Missing'
        Result '_downloadrestrictions' | Should -Be 'Missing'
        Result '_originkeyedprocessesenabled' | Should -Be 'Missing'
    }

    It 'reports Extra for non-Chrome settings and unexpected Chrome settings' {
        $edge = $Diff | Where-Object DefinitionId -like '*microsoft_edge*'
        $edge.Result | Should -Be 'Extra'
        $edge.Notes | Should -Match 'Not a Chrome'
        $amb = $Diff | Where-Object DefinitionId -eq "${P}~categorya_ambigpolicy"
        $amb.Result | Should -Be 'Extra'
        $amb.Notes | Should -Match 'CIS 1.8 is Ambiguous'
    }

    It 'covers every expected and every actual setting exactly once' {
        @($Diff | Where-Object Result -ne 'Extra').Count | Should -Be @($Mapped.Settings).Count
        @($Diff | Where-Object Result -ne 'Missing').Count | Should -Be @($Actual.settings).Count
    }

    It 'compares list values order-insensitively' {
        $exp = [ordered]@{ '@odata.type' = '#microsoft.graph.deviceManagementConfigurationSetting'; settingInstance = [ordered]@{
                '@odata.type' = '#microsoft.graph.deviceManagementConfigurationSimpleSettingCollectionInstance'; settingDefinitionId = 'x'
                simpleSettingCollectionValue = @(@{ value = 'a' }, @{ value = 'b' }) } }
        $act = [pscustomobject]@{ settings = @([pscustomobject]@{ settingInstance = [pscustomobject]@{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationSimpleSettingCollectionInstance'; settingDefinitionId = 'x'
                        simpleSettingCollectionValue = @([pscustomobject]@{ value = 'b' }, [pscustomobject]@{ value = 'a' }) } }) }
        (Compare-CisChromePolicy -ExpectedSettings @($exp) -Policy $act).Result | Should -Be 'Match'
    }
}

