        $rec.Recommended | Should -BeTrue
    }

    It 'formats registry references relative to Policies\Google' {
        (Get-FixturePolicy 'SyncDisabled').RegistryRef | Should -Be 'Chrome:SyncDisabled'
        (Get-FixturePolicy 'ExtensionInstallBlocklist').RegistryRef | Should -Be 'Chrome\ExtensionInstallBlocklist'
