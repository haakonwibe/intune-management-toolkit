BeforeAll {
    $script:ToolRoot = Split-Path -Parent $PSScriptRoot
    $script:Fixtures = Join-Path $PSScriptRoot 'fixtures'
    Import-Module (Join-Path $ToolRoot 'CisChromeCatalog.psm1') -Force
    . (Join-Path $Fixtures 'FixtureHelpers.ps1')

    $script:P = 'device_vendor_msft_policy_config_chromeintunev1~policy~googlechrome'
    $script:C = 'Software\Policies\Google\Chrome'
    $script:Defs = @(Get-Content (Join-Path $Fixtures 'definitions.json') -Raw | ConvertFrom-Json -Depth 50)
    $script:Index = New-ChromeDefinitionIndex -Definitions $Defs
    $script:Gpo = @(ConvertTo-ChromeGpoPolicy -Entries (Read-RegistryPolFile (Join-Path $Fixtures 'registry.pol')))
    $script:Recs = @(Import-CisBenchmarkWorkbook -Path (Join-Path $Fixtures 'workbook.xlsx'))

    function Get-FixturePolicy([string]$Name) { $script:Gpo | Where-Object PolicyName -eq $Name | Select-Object -First 1 }
    function Get-Def([string]$Suffix) { $script:Index.ById["$($script:P)$Suffix"] }
    function New-Pol([object[]]$Entries) {
        $path = Join-Path $TestDrive "$([guid]::NewGuid()).pol"
        Write-TestRegistryPol -Path $path -Entries $Entries
        $path
    }
}

Describe 'Read-RegistryPolFile' {
    It 'parses every entry of the fixture' {
        $e = @(Read-RegistryPolFile (Join-Path $Fixtures 'registry.pol'))
        $e.Count | Should -Be 17
        $sync = $e | Where-Object ValueName -eq 'SyncDisabled'
        $sync.Key | Should -Be $C
        $sync.TypeName | Should -Be 'REG_DWORD'
        $sync.Value | Should -Be 1
        ($e | Where-Object ValueName -eq 'ProxySettings').Value | Should -BeExactly '{"ProxyMode": "system"}'
        @($e | Where-Object ValueName -eq '**delvals.').Count | Should -Be 3
    }

    It 'decodes REG_EXPAND_SZ, REG_MULTI_SZ, REG_QWORD and REG_BINARY' {
        $path = New-Pol @(
            @{ Key = $C; ValueName = 'Exp'; Type = 'REG_EXPAND_SZ'; Value = '%ProgramFiles%\x' }
            @{ Key = $C; ValueName = 'Multi'; Type = 'REG_MULTI_SZ'; Value = @('a', 'b') }
            @{ Key = $C; ValueName = 'Q'; Type = 'REG_QWORD'; Value = 5000000000 }
            @{ Key = $C; ValueName = 'Bin'; Type = 'REG_BINARY'; Value = [byte[]](1, 2, 3) }
        )
        $e = Read-RegistryPolFile $path
        ($e | Where-Object ValueName -eq 'Exp').Value | Should -Be '%ProgramFiles%\x'
        ($e | Where-Object ValueName -eq 'Multi').Value | Should -Be @('a', 'b')
        ($e | Where-Object ValueName -eq 'Q').Value | Should -Be 5000000000
        ($e | Where-Object ValueName -eq 'Bin').Value | Should -Be @(1, 2, 3)
    }

    It 'rejects a file without the PReg signature' {
        $path = Join-Path $TestDrive 'bad.pol'
        [IO.File]::WriteAllBytes($path, [byte[]](1, 2, 3, 4, 1, 0, 0, 0))
        { Read-RegistryPolFile $path } | Should -Throw '*PReg*'
    }

    It 'rejects a truncated file' {
        $path = New-Pol @(@{ Key = $C; ValueName = 'SyncDisabled'; Type = 'REG_DWORD'; Value = 1 })
        $bytes = [IO.File]::ReadAllBytes($path)
        [IO.File]::WriteAllBytes($path, $bytes[0..($bytes.Length - 5)])
        { Read-RegistryPolFile $path } | Should -Throw '*Malformed*'
    }
}

