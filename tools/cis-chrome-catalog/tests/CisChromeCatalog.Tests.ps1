        (Get-FixturePolicy 'AutoUpdateCheckPeriodMinutes').RegistryRef | Should -Be 'Update:AutoUpdateCheckPeriodMinutes'
    }

    It 'orders list entries numerically, not lexically' {
        $path = New-Pol @(
            @{ Key = "$C\L"; ValueName = '**delvals.'; Type = 'REG_SZ'; Value = ' ' }
            @{ Key = "$C\L"; ValueName = '10'; Type = 'REG_SZ'; Value = 'ten' }
