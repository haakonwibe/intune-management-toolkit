    It 'classifies the fixture policies' {
        (Get-FixturePolicy 'SyncDisabled').Kind | Should -Be 'Scalar'
        (Get-FixturePolicy 'ExtensionInstallBlocklist').Kind | Should -Be 'List'
        (Get-FixturePolicy 'ExtensionInstallBlocklist').Value | Should -Be @('*')
        (Get-FixturePolicy 'CertificateTransparencyEnforcementDisabledForCas').Kind | Should -Be 'Disabled'
        (Get-FixturePolicy 'AutoUpdateCheckPeriodMinutes').Kind | Should -Be 'OutOfScope'
        $rec = Get-FixturePolicy 'OriginKeyedProcessesEnabled'
